/**
 * Stable execution identity, independent of any channel credential.
 *
 * A Principal is only ever constructed by trusted server code (the channel
 * directory or a Butler re-reading its persisted binding). Model tool
 * arguments never carry `actor`, `role` or `epoch`.
 */
export type Principal = {
  memberId: string;
  role: "owner" | "member";
  epoch: number;
};

export const OWNER_ID = "owner";

/**
 * One WeChat connection: which member, which connection row, which run.
 * The generation guards late callbacks from a replaced credential.
 */
export type ConnectionRef = {
  memberId: string;
  connectionId: string;
  generation: number;
};

/** What an actor may do, before the directory's liveness check. */
export type MemberCapability =
  | "ordinary-task"
  | "manage-members"
  | "prepare-share";

/**
 * A member id is `m` plus 32 lowercase hex characters, generated by the
 * server. Labels are display-only and never authorize anything.
 */
export const MEMBER_ID_PATTERN = /^m[0-9a-f]{32}$/;

/**
 * The task id grammar shared by the text-action parser and artifact keys.
 * Owner tasks keep the historical `tN`; member tasks are namespaced by their
 * stable member id so two members' counters cannot collide.
 */
export const TASK_ID_SOURCE = "(?:t\\d+|m[0-9a-f]{32}-t\\d+)";

export function taskIdPattern(): RegExp {
  return new RegExp(`^${TASK_ID_SOURCE}$`);
}

/** True for both the legacy `tN` and the member `m<32hex>-tN` form. */
export function isTaskId(value: string): boolean {
  return taskIdPattern().test(value);
}

export function butlerName(memberId: string): string {
  return memberId === OWNER_ID ? OWNER_ID : `member:${memberId}`;
}

export function newTaskId(actor: Principal, counter: number): string {
  return actor.memberId === OWNER_ID
    ? `t${counter}`
    : `${actor.memberId}-t${counter}`;
}

export function can(actor: Principal, capability: MemberCapability): boolean {
  switch (capability) {
    case "ordinary-task":
    case "prepare-share":
      // Still gated by the directory's active-principal check at call time.
      return true;
    case "manage-members":
      return actor.memberId === OWNER_ID && actor.role === "owner";
    default:
      return false;
  }
}

/** The owner principal used by legacy owner-only call sites. */
export function ownerPrincipal(): Principal {
  return { memberId: OWNER_ID, role: "owner", epoch: 1 };
}
