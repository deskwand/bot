/**
 * Generates the OpenCode Go model endpoint table used by ProbeModel.
 *
 * Usage:
 *   node --experimental-strip-types scripts/generate-opencode-models.ts
 *
 * Source:
 *   node_modules/@earendil-works/pi-ai/dist/providers/data/opencode-go.json
 * Output:
 *   desktop/internal/app/opencode_models_generated.go
 *
 * The table is checked by tests-node/opencode-models.test.ts so it cannot
 * drift from the installed pi-ai catalog.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export type OpenCodeModelEndpoint = {
  api: string;
  baseUrl: string;
};

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function requireString(value: unknown, label: string): string {
  if (typeof value !== "string" || value.length === 0) {
    throw new Error(`${label} must be a non-empty string`);
  }
  return value;
}

/** Builds a deterministic id → {api, baseUrl} map from the pi-ai catalog. */
export function buildOpenCodeGoTable(catalog: unknown): Map<string, OpenCodeModelEndpoint> {
  if (!isRecord(catalog)) {
    throw new Error("opencode-go catalog must be an object");
  }
  const table = new Map<string, OpenCodeModelEndpoint>();
  for (const [groupAPI, group] of Object.entries(catalog)) {
    if (!isRecord(group)) continue;
    for (const model of Object.values(group)) {
      if (!isRecord(model) || model.type !== "chat") continue;
      const id = requireString(model.id, "opencode-go model id");
      const api = typeof model.api === "string" && model.api.length > 0 ? model.api : groupAPI;
      const baseUrl = requireString(model.baseUrl, `opencode-go ${id} baseUrl`);
      if (table.has(id)) {
        throw new Error(`duplicate opencode-go model id: ${id}`);
      }
      table.set(id, { api, baseUrl });
    }
  }
  if (table.size === 0) {
    throw new Error("opencode-go catalog produced no chat models");
  }
  return new Map([...table.entries()].sort(([left], [right]) => left.localeCompare(right, "en")));
}

/** Renders the Go source. Keep one entry per line for the drift test. */
export function renderOpenCodeGoTable(table: Map<string, OpenCodeModelEndpoint>): string {
  const lines = [
    "// Code generated by scripts/generate-opencode-models.ts from",
    "// node_modules/@earendil-works/pi-ai/dist/providers/data/opencode-go.json.",
    "// Regenerate with:",
    "//   node --experimental-strip-types scripts/generate-opencode-models.ts",
    "//   gofmt -w desktop/internal/app/opencode_models_generated.go",
    "// Do not edit by hand.",
    "package app",
    "",
    "type openCodeModelEndpoint struct {",
    "\tAPI     string",
    "\tBaseURL string",
    "}",
    "",
    "var openCodeGoModelEndpoints = map[string]openCodeModelEndpoint{",
  ];
  for (const [id, endpoint] of table) {
    lines.push(
      `\t${JSON.stringify(id)}: {API: ${JSON.stringify(endpoint.api)}, BaseURL: ${JSON.stringify(endpoint.baseUrl)}},`,
    );
  }
  lines.push("}", "");
  return lines.join("\n");
}

export const CATALOG_PATH = resolve(
  "node_modules/@earendil-works/pi-ai/dist/providers/data/opencode-go.json",
);
export const OUTPUT_PATH = resolve("desktop/internal/app/opencode_models_generated.go");

function writeGeneratedTable(): void {
  const catalog: unknown = JSON.parse(readFileSync(CATALOG_PATH, "utf8"));
  const table = buildOpenCodeGoTable(catalog);
  writeFileSync(OUTPUT_PATH, renderOpenCodeGoTable(table));
  console.log(`Wrote ${table.size} OpenCode Go model endpoints to ${OUTPUT_PATH}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeGeneratedTable();
}
